-- =====================================================================
-- Vistoria Inteligente com IA — modelo de dados
-- SQL portável: roda no PostgreSQL (produção) e no H2 em modo PostgreSQL (dev/testes).
-- =====================================================================

-- Restaurantes (filiais) da rede
CREATE TABLE unidade (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        VARCHAR(120) NOT NULL UNIQUE,
    endereco    VARCHAR(200),
    cidade      VARCHAR(80),
    uf          VARCHAR(2),
    ativa       BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Normas regulamentadoras (NR). "ativa = false" => revogada/desatualizada => item reprovado.
CREATE TABLE norma_regulamentadora (
    codigo      VARCHAR(10)  PRIMARY KEY,           -- ex.: NR-23
    titulo      VARCHAR(200) NOT NULL,
    ativa       BOOLEAN      NOT NULL,
    observacao  VARCHAR(300)
);

-- Uma visita do técnico a uma unidade (o "checklist")
CREATE TABLE vistoria (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unidade_id     BIGINT       NOT NULL REFERENCES unidade (id),
    tecnico        VARCHAR(120) NOT NULL,
    data_vistoria  DATE         NOT NULL,
    criado_em      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_vistoria_unidade ON vistoria (unidade_id);

-- Cada foto/arquivo enviado e o parecer do sistema sobre ele
CREATE TABLE item_verificado (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vistoria_id            BIGINT        NOT NULL REFERENCES vistoria (id),
    tipo_esperado          VARCHAR(40),                    -- o que o técnico disse que fotografou
    tipo_item              VARCHAR(40),                    -- o que foi reconhecido
    localizacao            VARCHAR(60),
    status                 VARCHAR(20)   NOT NULL,         -- CONFORME | NAO_CONFORME | REVISAO_MANUAL
    urgencia               VARCHAR(10)   NOT NULL,         -- BAIXA | MEDIA | ALTA | CRITICA
    classificacao_risco    VARCHAR(20),
    norma_codigo           VARCHAR(10)   REFERENCES norma_regulamentadora (codigo),
    data_validade          DATE,
    resumo                 VARCHAR(1000) NOT NULL,
    -- evidência
    arquivo_nome           VARCHAR(200)  NOT NULL,
    arquivo_tipo           VARCHAR(50)   NOT NULL,
    arquivo_caminho        VARCHAR(300)  NOT NULL,
    -- OpenCV
    nitidez                DOUBLE PRECISION,
    brilho                 DOUBLE PRECISION,
    contraste              DOUBLE PRECISION,
    -- Tesseract
    texto_ocr              TEXT,
    confianca_ocr          DOUBLE PRECISION,
    -- IA
    origem_extracao        VARCHAR(20)   NOT NULL,         -- LLM | REGEX | REGEX_FALLBACK | NENHUMA
    json_extraido          TEXT,
    confianca_extracao     DOUBLE PRECISION,
    tempo_processamento_ms BIGINT        NOT NULL,
    -- revisão humana (supervisor)
    status_automatico      VARCHAR(20)   NOT NULL,         -- parecer original da máquina, nunca é alterado
    revisado_por           VARCHAR(120),
    observacao_revisao     VARCHAR(1000),
    revisado_em            TIMESTAMP,
    criado_em              TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_item_vistoria ON item_verificado (vistoria_id);
CREATE INDEX idx_item_status   ON item_verificado (status);

-- Motivos (apontamentos das regras) que explicam o parecer
CREATE TABLE motivo_validacao (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id          BIGINT        NOT NULL REFERENCES item_verificado (id) ON DELETE CASCADE,
    codigo_regra     VARCHAR(40)   NOT NULL,
    severidade       VARCHAR(10)   NOT NULL,               -- REPROVA | REVISAO | ALERTA
    mensagem_simples VARCHAR(500)  NOT NULL,
    detalhe_tecnico  VARCHAR(500)
);
CREATE INDEX idx_motivo_item ON motivo_validacao (item_id);

-- Auditoria de cada chamada ao LLM (custo, latência, falhas) — entidade específica de IA
CREATE TABLE chamada_ia (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id         BIGINT        NOT NULL REFERENCES item_verificado (id) ON DELETE CASCADE,
    provedor        VARCHAR(200)  NOT NULL,
    modelo          VARCHAR(80)   NOT NULL,
    versao_prompt   VARCHAR(40)   NOT NULL,
    sucesso         BOOLEAN       NOT NULL,
    erro            VARCHAR(500),
    tentativas      INT           NOT NULL,
    latencia_ms     BIGINT        NOT NULL,
    tokens_entrada  INT,
    tokens_saida    INT,
    resposta_bruta  TEXT,
    criado_em       TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_chamada_item ON chamada_ia (item_id);
